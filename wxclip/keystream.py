"""ISAAC64 keystream - the one and only thing a decode_key is for.

The reference implementation ships this as `electron/decrypt.js`: 5.2 MB of Emscripten
output whose single export, `getDecryptionArray(seed)`, hands back 131072 bytes. Behind
the wasm it is plain ISAAC64 (Bob Jenkins' generator, public domain), seeded by dropping
the decode_key into the first slot of the result array and emitting each 64-bit word most
significant byte first. Ported here so wxclip needs neither Node nor the blob.

The port is not taken on trust: `evals/README.md` records the sha256 of five keystreams
generated by `decrypt.js` itself, `tests/test_keystream.py` checks this module against
all five, and `tools/keystream-golden.mjs` regenerates the table when the reference
implementation moves.

The seed reaches `int()` here and nowhere else. It is a 64-bit integer arriving as a
decimal string, and a string is what it has to stay: one trip through a float turns
13835058055282163712 into 13835058055282164000, which yields a keystream with nothing in
common with the right one and not a single error along the way.
"""

from __future__ import annotations

#: Bytes of a downloaded file that are encrypted: 128 KiB. Everything past this offset is
#: stored in the clear, which is why the tail of a truncated download needs no keystream.
HEAD_BYTES = 131072

_MASK = 0xFFFFFFFFFFFFFFFF
#: ISAAC64 state size, in 64-bit words.
_SIZE = 256
#: The golden ratio, which is what isaac64.c seeds its mixing registers with.
_GOLDEN = 0x9E3779B97F4A7C13

#: The four shifts `a` cycles through inside a round - isaac64.c spells them out as four
#: consecutive `rngstep` invocations, and their order is part of the algorithm.
_SHIFTS = (
    lambda a: ~(a ^ ((a << 21) & _MASK)) & _MASK,
    lambda a: a ^ (a >> 5),
    lambda a: a ^ ((a << 12) & _MASK),
    lambda a: a ^ (a >> 33),
)


class KeystreamError(ValueError):
    """The decode_key is not something a keystream can be derived from."""


def parse_decode_key(decode_key: str) -> int:
    """A decode_key is a decimal string holding a uint64. Anything else is a bug upstream
    - most likely a JSON parser that turned it into a float - and is worth stopping for."""
    if not isinstance(decode_key, str):
        raise KeystreamError(f"decode_key must be a string, got {type(decode_key).__name__}")
    key = decode_key.strip()
    if not key.isdigit():
        raise KeystreamError(
            f"decode_key must be decimal digits, got {decode_key!r} - "
            "a value in exponent or float form has already lost its low digits"
        )
    value = int(key)
    if value > _MASK:
        raise KeystreamError(f"decode_key {key} does not fit in 64 bits")
    return value


def _mix(s: list[int]) -> None:
    """isaac64.c's `mix`, in place over eight registers."""
    a, b, c, d, e, f, g, h = s
    a = (a - e) & _MASK
    f ^= h >> 9
    h = (h + a) & _MASK
    b = (b - f) & _MASK
    g ^= (a << 9) & _MASK
    a = (a + b) & _MASK
    c = (c - g) & _MASK
    h ^= b >> 23
    b = (b + c) & _MASK
    d = (d - h) & _MASK
    a ^= (c << 15) & _MASK
    c = (c + d) & _MASK
    e = (e - a) & _MASK
    b ^= d >> 14
    d = (d + e) & _MASK
    f = (f - b) & _MASK
    c ^= (e << 20) & _MASK
    e = (e + f) & _MASK
    g = (g - c) & _MASK
    d ^= f >> 17
    f = (f + g) & _MASK
    h = (h - d) & _MASK
    e ^= (g << 14) & _MASK
    g = (g + h) & _MASK
    s[:] = [a, b, c, d, e, f, g, h]


class Isaac64:
    """ISAAC64, seeded from the result array the way `randinit(ctx, TRUE)` expects.

    Values come out in the order `rand()` hands them over: the last slot of the result
    array first, down to the first. That order is not cosmetic - it is what makes seed 0
    start with 9d39247e33776d41, and getting it backwards produces a plausible-looking
    stream that decrypts nothing.
    """

    def __init__(self, seed: int = 0) -> None:
        self.mm = [0] * _SIZE
        self.rsl = [0] * _SIZE
        self.rsl[0] = seed & _MASK
        self.aa = self.bb = self.cc = 0
        self._init()

    def _init(self) -> None:
        s = [_GOLDEN] * 8
        for _ in range(4):
            _mix(s)
        for i in range(0, _SIZE, 8):
            for j in range(8):
                s[j] = (s[j] + self.rsl[i + j]) & _MASK
            _mix(s)
            self.mm[i : i + 8] = s
        # Second pass: the seed has to influence every word of the state, not just the
        # eight registers it was folded into above.
        for i in range(0, _SIZE, 8):
            for j in range(8):
                s[j] = (s[j] + self.mm[i + j]) & _MASK
            _mix(s)
            self.mm[i : i + 8] = s
        self._step()
        self._left = _SIZE

    def _step(self) -> None:
        """One ISAAC64 round: refill all 256 result words."""
        mm = self.mm
        rsl = self.rsl
        a = self.aa
        self.cc = (self.cc + 1) & _MASK
        b = (self.bb + self.cc) & _MASK
        half = _SIZE // 2
        # Each word is mixed with its opposite number in the other half of the state:
        # the first half reads from the second, then the second half reads from the first.
        for base, other in ((0, half), (half, 0)):
            for i in range(0, half, 4):
                for k, shift in enumerate(_SHIFTS):
                    a = shift(a)
                    index = base + i + k
                    x = mm[index]
                    a = (a + mm[other + i + k]) & _MASK
                    # isaac64.c indexes mm by a byte offset (`x & ((RANDSIZ-1) << 3)`),
                    # so the word index is three bits further up than it looks.
                    y = (mm[(x >> 3) & (_SIZE - 1)] + a + b) & _MASK
                    mm[index] = y
                    b = (mm[(y >> 11) & (_SIZE - 1)] + x) & _MASK
                    rsl[index] = b
        self.aa = a
        self.bb = b

    def next(self) -> int:
        if self._left == 0:
            self._step()
            self._left = _SIZE
        self._left -= 1
        return self.rsl[self._left]


def keystream(decode_key: str, length: int = HEAD_BYTES) -> bytes:
    """The bytes to XOR over the head of the downloaded file.

    `decode_key` stays a string all the way in; `length` is only a parameter so tests can
    ask for a short stream, and it is always `HEAD_BYTES` in practice.
    """
    if length < 0:
        raise KeystreamError(f"length must not be negative, got {length}")
    generator = Isaac64(parse_decode_key(decode_key))
    out = bytearray()
    while len(out) < length:
        out += generator.next().to_bytes(8, "big")
    return bytes(out[:length])
